#!/usr/bin/env python3
"""Generate the DEV catalog from gameplay items and actual committed interior GLB bounds."""
import csv,json,hashlib,sys
from pathlib import Path
from gltf_import import read_gltf,scene_bounds
ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'include/outland/creator/EconomyAssetCatalog.hpp'
def generate():
    lines=['#pragma once','// Generated by tools/generate_interior_catalog.py from the gameplay item catalog.','#ifdef OUTLAND_DEV_TOOLS','#include "outland/creator/CreatorAssetRegistry.hpp"','namespace outland::creator {','inline void register_economy_assets(CreatorAssetRegistry& registry) {']
    models=set()
    with (ROOT/'assets/verda/survival/gameplay/items.tsv').open() as stream:
        for item in csv.DictReader(stream,delimiter='\t'):
            if not item['model'].startswith('assets/verda/interiors/props/'):continue
            path=ROOT/item['model'];document,binary=read_gltf(path);low,high=scene_bounds(document)
            assert binary and document.get('meshes') and path not in models
            models.add(path)
            assert document.get('images') and all('bufferView' in image and 'uri' not in image for image in document['images'])
            dimensions=[high[0]-low[0],high[2]-low[2],high[1]-low[1]]
            assert max(dimensions)>0
            dimensions=[max(.03,value) for value in dimensions]
            footprint=','.join(f'{value:.6f}F' for value in dimensions)
            lines.extend(['    (void)registry.add({',f'        .id={json.dumps("economy_"+item["id"])}, .name={json.dumps(item["name"])},',f'        .category=CreatorAssetCategory::Prop, .model_path={json.dumps(item["model"])}, .thumbnail_path="",',f'        .footprint={{{footprint}}}, .placement={{}}, .default_scale=1.0F, .tags={{"interiors","economy","prop"}}','    });'])
    assert models==set((ROOT/'assets/verda/interiors/props').glob('*.glb')), 'An interior model is missing from the gameplay catalog'
    lines.extend(['}','}','#endif'])
    return '\n'.join(lines)+'\n'
text=generate()
if '--check' in sys.argv:
    assert OUTPUT.read_text()==text, 'Run tools/generate_interior_catalog.py'
    print('Interior catalog: all 43 committed textured models are purchasable and DEV-placeable')
else:
    OUTPUT.write_text(text)
